opcua_model_context_t *model_context_get(void)
{
    return &g_model_context;
}

void model_context_set_server_handles(UA_Server *server, UA_ServerConfig *config)
{
    g_model_context.server = server;
    g_model_context.server_config = config;
}

void model_context_delete_server(UA_Server *server)
{
    if (server == NULL)
    {
        return;
    }

    if (g_model_context.server == server)
    {
        g_model_context.server = NULL;
        g_model_context.server_config = NULL;
    }

    UA_Server_delete(server);
}
