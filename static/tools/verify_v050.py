#!/usr/bin/env python3
"""Safe, reversible on-device verification for v0.5.0 configuration transactions.

The verifier intentionally changes only two fields on an already configured
channel: ``alarmHysteresis`` (which must not restart the OPC UA server) and
``description`` (which must).  It never changes network, OPC UA port, MAC,
driver, value type, security, trust, OTA, or history settings.  The separate,
explicit ``--verify-presets`` mode temporarily applies the three documented
runtime presets and restores the original export after each one.

Every uploaded document is generated by stage_config's canonicalizer.  The
original export is retained in memory and is restored on every exit path.  A
JSON evidence file is written even when the verification fails.
"""

from __future__ import annotations

import argparse
import asyncio
import copy
from datetime import datetime, timezone
import getpass
import hashlib
import json
from pathlib import Path
import sys
import time
import zlib

import stage_config as opcua_common


MAINTENANCE_CONFIGURATION_NODE_ID = opcua_common.CONFIGURATION_NODE_ID
CONFIGURATION_NODE_ID = opcua_common.CONFIGURATION_NODE_ID
SYSTEM_NODE_ID = opcua_common.SYSTEM_NODE_ID
IDENTITY_NODES = {
    "deviceName": "Device.Identification.DeviceName",
    "model": "Device.Identification.Model",
    "serialNumber": "Device.Identification.SerialNumber",
    "hardwareRevision": "Device.Identification.HardwareRevision",
    "softwareRevision": "Device.Identification.SoftwareRevision",
    "gitHash": "Device.Identification.GitHash",
}
COMPATIBILITY_NODES = {
    "firmwareProfile": "Device.Compatibility.FirmwareProfile",
    "hardwareRevision": "Device.Compatibility.HardwareRevision",
    "configurationSchemaVersion": "Device.Compatibility.ConfigurationSchemaVersion",
}
METHOD_LIST_CONFIG_PRESETS = "ns=1;s=Device.Maintenance.ListConfigPresets"
METHOD_APPLY_CONFIG_PRESET = "ns=1;s=Device.Maintenance.ApplyConfigPreset"
REQUIRED_PRESET_NAMES = ("sensor_node", "remote_io", "dev_benchmark")
FUTURE_SCHEMA_OFFSET = 1
MAX_UPLOAD_CHUNK_BYTES = opcua_common.DEFAULT_CHUNK_SIZE


class VerificationError(RuntimeError):
    """A protocol-visible v0.5.0 contract did not hold."""


class Evidence:
    def __init__(self, endpoint: str):
        self.payload = {
            "tool": "verify_v050.py",
            "startedUtc": utc_now(),
            "endpoint": endpoint,
            "passed": [],
            "failed": [],
            "observations": {},
            "restore": {"attempted": False, "restored": False},
        }

    def passed(self, name: str, **details) -> None:
        self.payload["passed"].append({"name": name, **details})

    def failed(self, name: str, error: BaseException | str) -> None:
        self.payload["failed"].append({"name": name, "error": str(error)})

    def write(self, path: Path, success: bool) -> None:
        self.payload["finishedUtc"] = utc_now()
        self.payload["success"] = success
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(self.payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


class DataChangeCounter:
    """Bounded subscription evidence; no value payloads are retained."""

    def __init__(self):
        self.notifications = 0

    def datachange_notification(self, node, value, data) -> None:  # asyncua callback signature
        del node, value, data
        self.notifications += 1


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def parse_endpoint(value: str) -> str:
    """Fail closed to the OPC TCP endpoint grammar used by stage_config."""
    from urllib.parse import urlparse

    parsed = urlparse(value)
    if parsed.scheme != "opc.tcp" or not parsed.hostname or parsed.port is None:
        raise argparse.ArgumentTypeError("endpoint must be opc.tcp://HOST:PORT")
    if parsed.username or parsed.password or parsed.path not in ("", "/") or parsed.query or parsed.fragment:
        raise argparse.ArgumentTypeError("endpoint must contain only opc.tcp://HOST:PORT")
    return value


def build_parser() -> argparse.ArgumentParser:
    common = opcua_common.build_common_parser()
    parser = argparse.ArgumentParser(
        description=__doc__, parents=[common],
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    # Reuse stage_config's exact endpoint/credentials/security arguments, then
    # additionally reject URL forms that could accidentally embed credentials.
    for action in parser._actions:
        if action.dest == "server_url":
            action.type = parse_endpoint
    parser.add_argument("--evidence", type=Path, default=Path("build/verify_v050.json"),
                        help="JSON evidence output (default: build/verify_v050.json)")
    parser.add_argument("--recovery-export", type=Path,
                        default=Path("build/verify_v050_recovery_export.json"),
                        help="canonical baseline export retained for manual recovery if this process is interrupted")
    parser.add_argument("--reconnect-timeout", type=float, default=45.0,
                        help="bounded reconnect timeout after a controlled restart")
    parser.add_argument("--reconnect-interval", type=float, default=0.5,
                        help="retry period while reconnecting (seconds)")
    parser.add_argument("--stability-timeout", type=float, default=45.0,
                        help="bounded wait for GetConfigState to settle after a controlled restart")
    parser.add_argument("--stability-interval", type=float, default=0.5,
                        help="GetConfigState poll period while waiting for stable restart state (seconds)")
    parser.add_argument("--disconnect-timeout", type=float, default=5.0,
                        help="maximum time the pre-transaction session may survive a required server restart")
    parser.add_argument("--reboot-verify", action="store_true",
                        help="explicitly request normal Reboot and verify the restored config survives it")
    parser.add_argument("--verify-presets", action="store_true",
                        help="opt in to applying sensor_node, remote_io and dev_benchmark; restores baseline after each")
    parser.add_argument("--expected-software-revision",
                        help="require Device.Identification.SoftwareRevision to match exactly")
    return parser


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    args = build_parser().parse_args(argv)
    if (args.timeout <= 0 or args.reconnect_timeout <= 0 or args.reconnect_interval <= 0
            or args.stability_timeout <= 0 or args.stability_interval <= 0
            or args.disconnect_timeout <= 0):
        raise ValueError("timeout and reconnect values must be positive")
    return args


def canonical_payload(document: dict) -> tuple[dict, bytes, int]:
    canonical = opcua_common.canonicalize_config_document(document)
    payload = opcua_common.serialize_canonical_document(canonical).encode("utf-8")
    return canonical, payload, zlib.crc32(payload) & 0xFFFFFFFF


def document_hash(document: dict) -> str:
    _, payload, _ = canonical_payload(document)
    return hashlib.sha256(payload).hexdigest()


def select_numeric_channel(document: dict) -> dict:
    for channel in document["channels"]:
        # telemetry_channel_value_type_t: BOOLEAN=6, STRING=7.  Everything
        # else is numeric and has the alarm-hysteresis contract under test.
        if channel["inUse"] and int(channel["valueType"]) < 6:
            return channel
    raise VerificationError("no in-use numeric channel is available for alarmHysteresis test")


def make_no_restart_candidate(baseline: dict) -> tuple[dict, int]:
    candidate = copy.deepcopy(baseline)
    channel = select_numeric_channel(candidate)
    previous = float(channel["alarmHysteresis"])
    # Reducing a nonzero hysteresis remains inside any existing upper bound;
    # a zero value gets the smallest representable test delta.
    channel["alarmHysteresis"] = previous / 2.0 if previous != 0.0 else 0.001
    return candidate, int(channel["slot"])


def make_restart_candidate(baseline: dict) -> tuple[dict, int, str]:
    candidate = copy.deepcopy(baseline)
    channel = select_numeric_channel(candidate)
    previous = str(channel["description"])
    # Keep the exact existing string length so an already-full fixed C field
    # cannot make this otherwise harmless model change fail validation.
    if previous:
        first = "V" if previous[0] != "V" else "v"
        channel["description"] = first + previous[1:]
    else:
        channel["description"] = "v"
    return candidate, int(channel["slot"]), channel["description"]


def make_missing_driver_candidate(baseline: dict, installed_ids: set[int] | None = None) -> tuple[dict, int, int]:
    candidate = copy.deepcopy(baseline)
    channel = select_numeric_channel(candidate)
    installed_ids = installed_ids or set()
    missing_id = next((driver_id for driver_id in range(1, 256)
                       if driver_id not in installed_ids), None)
    if missing_id is None:
        raise VerificationError("every uint8 driver id is unexpectedly installed")
    # driverId is deliberately an on-wire uint8.  Select an actually absent
    # value from the device's own SupportedDrivers inventory, never assume a
    # particular compile-time driver pack.
    channel["driverId"] = missing_id
    return candidate, int(channel["slot"]), missing_id


def required_preset_names(catalog: object) -> tuple[str, ...]:
    """Validate the catalog shape, then select only v0.5.0's three presets."""
    if not isinstance(catalog, list):
        raise VerificationError("ListConfigPresets did not return a JSON array")
    names: list[str] = []
    for entry in catalog:
        if not isinstance(entry, dict) or not isinstance(entry.get("name"), str):
            raise VerificationError(f"ListConfigPresets contains invalid entry: {entry!r}")
        names.append(entry["name"])
    if len(names) != len(set(names)):
        raise VerificationError(f"ListConfigPresets contains duplicate names: {names!r}")
    missing = [name for name in REQUIRED_PRESET_NAMES if name not in names]
    if missing:
        raise VerificationError(f"ListConfigPresets is missing required presets: {missing!r}")
    return REQUIRED_PRESET_NAMES


def active_channel_inventory(document: dict) -> dict:
    """Return bounded evidence that an exported preset is populated and coherent."""
    canonical = opcua_common.canonicalize_config_document(document)
    active = [channel for channel in canonical["channels"] if channel["inUse"]]
    ids = [str(channel["id"]) for channel in active]
    if not active:
        raise VerificationError("preset export contains no in-use channels")
    if any(not channel_id for channel_id in ids) or len(ids) != len(set(ids)):
        raise VerificationError(f"preset export has invalid or duplicate active ids: {ids!r}")
    return {"channelCount": len(active), "channelIds": ids}


def stable_config_state(state: object) -> dict:
    """Reject half-applied/import-active state after a preset transaction."""
    if not isinstance(state, dict):
        raise VerificationError(f"GetConfigState did not return an object: {state!r}")
    required = ("runningRevision", "stagedRevision", "stagedDiffers", "importSessionActive")
    missing = [key for key in required if key not in state]
    if missing:
        raise VerificationError(f"GetConfigState missing required fields: {missing!r}")
    stable = (
        int(state["runningRevision"]) == int(state["stagedRevision"])
        and not bool(state["stagedDiffers"])
        and not bool(state["importSessionActive"])
        and not bool(state.get("rebootRequired", False))
    )
    if not stable:
        raise VerificationError(f"GetConfigState is not stable: {state}")
    return {
        "runningRevision": int(state["runningRevision"]),
        "stagedRevision": int(state["stagedRevision"]),
        "rebootRequired": bool(state.get("rebootRequired", False)),
    }


def config_state_snapshot(state: object) -> dict:
    """Keep only bounded, useful state evidence while a restart settles."""
    if not isinstance(state, dict):
        return {"nonObjectState": repr(state)[:160]}
    keys = (
        "runningRevision", "stagedRevision", "stagedDiffers", "importSessionActive",
        "rebootRequired", "importLastResult",
    )
    return {key: state[key] for key in keys if key in state}


async def call_string(object_node, method_id: str, *inputs):
    return await opcua_common.call_string_method(object_node, method_id, *inputs)


async def read_export(configuration) -> dict:
    exported = await opcua_common.export_config(configuration)
    return opcua_common.canonicalize_config_document(exported)


async def connect(args):
    return await opcua_common.connect_client(args)


async def disconnect_quietly(client) -> None:
    if client is None:
        return
    try:
        await client.disconnect()
    except Exception:
        pass


async def reconnect_until(args, evidence: Evidence, label: str, deadline: float | None = None):
    deadline = deadline if deadline is not None else time.monotonic() + args.reconnect_timeout
    attempts = 0
    last_error = None
    while time.monotonic() < deadline:
        attempts += 1
        client = None
        try:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                break
            client = await asyncio.wait_for(connect(args), timeout=remaining)
            evidence.passed(label, attempts=attempts)
            return client
        except Exception as exc:
            last_error = exc
            await disconnect_quietly(client)
            await asyncio.sleep(args.reconnect_interval)
    raise VerificationError(f"{label}: no reconnect in {args.reconnect_timeout}s: {last_error}")


async def require_server_disconnect(args, configuration, evidence: Evidence, label: str) -> None:
    """Prove a controlled restart closed the pre-transaction OPC UA session."""
    deadline = time.monotonic() + args.disconnect_timeout
    reads = 0
    last_state = None
    while time.monotonic() < deadline:
        try:
            last_state = config_state_snapshot(
                await opcua_common.get_config_state(configuration))
            reads += 1
        except Exception as exc:
            evidence.passed(label, readsBeforeDisconnect=reads,
                            disconnectException=str(exc)[:160])
            return
        await asyncio.sleep(min(0.1, max(0.0, deadline - time.monotonic())))
    raise VerificationError(
        f"{label}: pre-transaction session remained usable for "
        f"{args.disconnect_timeout}s ({reads} reads, last state {last_state})"
    )


async def wait_for_stable_config_state(args, client, ua, evidence: Evidence, label: str):
    """Wait through deferred restart state; timeout is a hard verification failure.

    A TCP/secure-channel reconnect can succeed before the old server instance
    has completed its deferred teardown.  Therefore a successful socket is
    not evidence by itself: this waits for a stable running/staged state,
    reconnecting if that in-between server closes the session.
    """
    deadline = time.monotonic() + args.stability_timeout
    report = {"transientStates": [], "reconnectAttempts": 0, "pollAttempts": 0}
    evidence.payload["observations"].setdefault("configStateStability", {})[label] = report
    while time.monotonic() < deadline:
        report["pollAttempts"] += 1
        try:
            configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
            raw_state = await opcua_common.get_config_state(configuration)
            try:
                stable = stable_config_state(raw_state)
            except VerificationError:
                if len(report["transientStates"]) < 16:
                    report["transientStates"].append(config_state_snapshot(raw_state))
                await asyncio.sleep(min(args.stability_interval,
                                        max(0.0, deadline - time.monotonic())))
                continue
            report["stableState"] = stable
            evidence.passed("config-state-stable", label=label, **report)
            return client, stable
        except Exception as exc:
            if len(report["transientStates"]) < 16:
                report["transientStates"].append({"connectionError": str(exc)[:160]})
            await disconnect_quietly(client)
            report["reconnectAttempts"] += 1
            if time.monotonic() >= deadline:
                break
            try:
                client = await reconnect_until(args, evidence, f"{label}-reconnect", deadline)
            except Exception as reconnect_exc:
                report["lastReconnectError"] = str(reconnect_exc)[:160]
                break
    await disconnect_quietly(client)
    raise VerificationError(
        f"{label}: GetConfigState did not become stable within "
        f"{args.stability_timeout}s: {report}"
    )


async def upload_and_validate(configuration, ua, document: dict, *, schema_version: int,
                              expect_valid: bool, apply: bool) -> dict:
    """Own one import session and close it on all non-applied paths."""
    canonical, payload, crc32 = canonical_payload(document)
    del canonical
    if len(payload) > 0xFFFFFFFF:
        raise VerificationError("canonical configuration exceeds UInt32 upload size")
    started = False
    try:
        status = await opcua_common.get_config_state(configuration)
        max_chunk = min(int(status.get("importMaxChunkBytes", MAX_UPLOAD_CHUNK_BYTES)),
                        MAX_UPLOAD_CHUNK_BYTES)
        if max_chunk <= 0:
            raise VerificationError(f"invalid importMaxChunkBytes {max_chunk}")
        begun = await opcua_common.call_bool_method(
            configuration, opcua_common.METHOD_BEGIN_CONFIG_IMPORT,
            ua.Variant(len(payload), ua.VariantType.UInt32),
            ua.Variant(crc32, ua.VariantType.UInt32),
            ua.Variant(schema_version, ua.VariantType.UInt32),
        )
        if not begun:
            return {"begun": False, "valid": False, "report": None}
        started = True
        for offset in range(0, len(payload), max_chunk):
            accepted = await opcua_common.call_bool_method(
                configuration, opcua_common.METHOD_WRITE_CONFIG_CHUNK,
                ua.Variant(payload[offset:offset + max_chunk], ua.VariantType.ByteString),
            )
            if not accepted:
                raise VerificationError(f"WriteConfigChunk rejected at byte {offset}")
        report = await opcua_common.validate_imported_config(configuration)
        valid = bool(report.get("valid", False))
        if valid != expect_valid:
            raise VerificationError(f"unexpected validation result {valid}: {report}")
        if not valid or not apply:
            aborted = await opcua_common.call_bool_method(
                configuration, opcua_common.METHOD_ABORT_CONFIG_IMPORT)
            if not aborted:
                raise VerificationError("AbortConfigImport rejected verifier-owned session")
            started = False
            return {"begun": True, "valid": valid, "report": report}
        accepted = await opcua_common.call_bool_method(
            configuration, opcua_common.METHOD_APPLY_IMPORTED_CONFIG)
        if not accepted:
            raise VerificationError("ApplyImportedConfig returned false")
        started = False
        return {"begun": True, "valid": valid, "report": report, "applied": True}
    except Exception:
        if started:
            try:
                await opcua_common.call_bool_method(
                    configuration, opcua_common.METHOD_ABORT_CONFIG_IMPORT)
            except Exception:
                # The caller records the original exception.  A disconnect
                # can make abort impossible; it is never silently treated as
                # success because subsequent restoration must still prove hash.
                pass
        raise


async def assert_hash(configuration, expected_hash: str, label: str) -> dict:
    exported = await read_export(configuration)
    actual_hash = document_hash(exported)
    if actual_hash != expected_hash:
        raise VerificationError(f"{label}: config SHA-256 changed ({actual_hash} != {expected_hash})")
    return exported


async def capture_management_model(client, ua, evidence: Evidence) -> None:
    identity = {}
    for name, node_id in IDENTITY_NODES.items():
        identity[name] = str(await client.get_node(ua.NodeId(node_id, 1)).read_value())
    compatibility = {}
    for name, node_id in COMPATIBILITY_NODES.items():
        compatibility[name] = await client.get_node(ua.NodeId(node_id, 1)).read_value()

    supported_parent = client.get_node(ua.NodeId("Device.Compatibility.SupportedDrivers", 1))
    supported_drivers = {}
    for child in await supported_parent.get_children():
        browse_name = await child.read_browse_name()
        supported_drivers[browse_name.Name] = json.loads(str(await child.read_value()))
    if not supported_drivers:
        raise VerificationError("SupportedDrivers is empty")

    maintenance_configuration = client.get_node(
        ua.NodeId.from_string(MAINTENANCE_CONFIGURATION_NODE_ID))
    presets = json.loads(await call_string(
        maintenance_configuration, METHOD_LIST_CONFIG_PRESETS))
    configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
    state = await opcua_common.get_config_state(configuration)
    exported = await read_export(configuration)
    evidence.payload["observations"].update({
        "identity": identity,
        "compatibility": compatibility,
        "supportedDrivers": supported_drivers,
        "configPresets": presets,
        "initialConfigState": state,
        "initialConfigSha256": document_hash(exported),
    })
    evidence.passed("management-model-read", supportedDriverCount=len(supported_drivers))


async def verify_no_restart(client, ua, baseline: dict, baseline_hash: str, evidence: Evidence) -> None:
    candidate, slot = make_no_restart_candidate(baseline)
    configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
    # Namespace 2 is not stable, so browse only a known ns=1 config node as a
    # monitored item.  Its value is not expected to change; subscription
    # identity plus a successful in-session method/read prove it survives.
    monitored = client.get_node(ua.NodeId("Device.Compatibility.ConfigurationSchemaVersion", 1))
    counter = DataChangeCounter()
    subscription = await client.create_subscription(250, counter)
    handle = await subscription.subscribe_data_change(monitored)
    token_before = repr(getattr(client.uaclient.session, "authentication_token", None))
    subscription_id = getattr(subscription, "subscription_id", None)
    if token_before == "None" or subscription_id is None:
        raise VerificationError("asyncua did not expose the connected session/subscription identity")
    try:
        await upload_and_validate(configuration, ua, candidate,
                                  schema_version=int(candidate["schemaVersion"]),
                                  expect_valid=True, apply=True)
        token_after = repr(getattr(client.uaclient.session, "authentication_token", None))
        if token_after != token_before or getattr(subscription, "subscription_id", None) != subscription_id:
            raise VerificationError("no-restart transaction replaced session or subscription")
        await opcua_common.get_config_state(configuration)
        await monitored.read_value()
        await assert_hash(configuration, document_hash(candidate), "no-restart commit")
        evidence.passed("no-restart-transaction", channelSlot=slot,
                        subscriptionId=subscription_id, notifications=counter.notifications)
        await upload_and_validate(configuration, ua, baseline,
                                  schema_version=int(baseline["schemaVersion"]),
                                  expect_valid=True, apply=True)
        await assert_hash(configuration, baseline_hash, "no-restart restore")
    finally:
        try:
            await subscription.unsubscribe(handle)
        except Exception:
            pass
        try:
            await subscription.delete()
        except Exception:
            pass


async def verify_restart(args, client, ua, baseline: dict, baseline_hash: str, evidence: Evidence):
    candidate, slot, expected_description = make_restart_candidate(baseline)
    configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
    method_reply_disconnected = False
    try:
        await upload_and_validate(configuration, ua, candidate,
                                  schema_version=int(candidate["schemaVersion"]),
                                  expect_valid=True, apply=True)
        await require_server_disconnect(
            args, configuration, evidence, "restart-old-session-disconnected")
    except Exception as exc:
        # The deferred restart is allowed to close transport before asyncua
        # receives a Method response.  Reconnect and verify the committed hash
        # rather than classifying this expected transport effect as a failure.
        if isinstance(exc, VerificationError):
            raise
        method_reply_disconnected = True
        evidence.payload["observations"]["restartMethodReplyException"] = str(exc)
        await require_server_disconnect(
            args, configuration, evidence, "restart-old-session-disconnected")
    finally:
        await disconnect_quietly(client)

    reconnected = await reconnect_until(args, evidence, "restart-reconnect")
    try:
        reconnected, committed_state = await wait_for_stable_config_state(
            args, reconnected, ua, evidence, "restart-post-commit")
        configuration = reconnected.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        current = await assert_hash(configuration, document_hash(candidate), "restart commit")
        if current["channels"][slot]["description"] != expected_description:
            raise VerificationError("reconnected server did not expose changed channel description")
        evidence.passed("restart-transaction", channelSlot=slot,
                        methodReplyDisconnected=method_reply_disconnected,
                        state=committed_state)
        restore_reply_disconnected = False
        try:
            await upload_and_validate(configuration, ua, baseline,
                                      schema_version=int(baseline["schemaVersion"]),
                                      expect_valid=True, apply=True)
            await require_server_disconnect(
                args, configuration, evidence, "restart-restore-old-session-disconnected")
        except Exception as exc:
            if isinstance(exc, VerificationError):
                raise
            restore_reply_disconnected = True
            evidence.payload["observations"]["restartRestoreMethodReplyException"] = str(exc)
            await require_server_disconnect(
                args, configuration, evidence, "restart-restore-old-session-disconnected")
        evidence.payload["observations"]["restartRestoreMethodReplyDisconnected"] = restore_reply_disconnected
    finally:
        await disconnect_quietly(reconnected)

    restored = await reconnect_until(args, evidence, "restore-reconnect")
    try:
        restored, restored_state = await wait_for_stable_config_state(
            args, restored, ua, evidence, "restart-post-restore")
        configuration = restored.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        await assert_hash(configuration, baseline_hash, "restart restore")
        evidence.passed("restart-baseline-restored", state=restored_state)
        return restored
    except Exception:
        await disconnect_quietly(restored)
        raise


async def apply_preset_and_reconnect(args, client, ua, preset_name: str, evidence: Evidence):
    """Apply one preset, accepting a disconnect only after proving its commit."""
    client, before = await wait_for_stable_config_state(
        args, client, ua, evidence, f"preset-{preset_name}-pre-apply")
    configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
    method_reply_disconnected = False
    try:
        accepted = await opcua_common.call_bool_method(
            configuration,
            METHOD_APPLY_CONFIG_PRESET,
            ua.Variant(preset_name, ua.VariantType.String),
        )
        if not accepted:
            raise VerificationError(f"ApplyConfigPreset returned false for {preset_name}")
        await require_server_disconnect(
            args, configuration, evidence,
            f"preset-{preset_name}-old-session-disconnected")
    except Exception as exc:
        # A successful transaction that changes the model may tear down the
        # socket while asyncua is still awaiting the method response.  The
        # reconnect below distinguishes that expected case from a lost call.
        if isinstance(exc, VerificationError):
            raise
        method_reply_disconnected = True
        evidence.payload["observations"].setdefault("presetMethodReplyExceptions", {})[preset_name] = str(exc)
        await require_server_disconnect(
            args, configuration, evidence,
            f"preset-{preset_name}-old-session-disconnected")
    finally:
        await disconnect_quietly(client)

    reconnected = await reconnect_until(args, evidence, f"preset-{preset_name}-reconnect")
    try:
        reconnected, state = await wait_for_stable_config_state(
            args, reconnected, ua, evidence, f"preset-{preset_name}-post-apply")
        configuration = reconnected.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        if state["runningRevision"] == before["runningRevision"]:
            raise VerificationError(
                f"ApplyConfigPreset {preset_name} did not advance runningRevision "
                f"({state['runningRevision']})"
            )
        exported = await read_export(configuration)
        inventory = active_channel_inventory(exported)
        return reconnected, {
            "preset": preset_name,
            "methodReplyDisconnected": method_reply_disconnected,
            "state": state,
            **inventory,
        }
    except Exception:
        await disconnect_quietly(reconnected)
        raise


async def restore_preset_baseline(args, ua, baseline: dict, baseline_hash: str,
                                  preset_name: str, evidence: Evidence):
    """Restore the original running config, then prove stable reconnect state."""
    client = await reconnect_until(args, evidence, f"preset-{preset_name}-restore-connect")
    try:
        configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        current = await read_export(configuration)
        if document_hash(current) != baseline_hash:
            try:
                await upload_and_validate(configuration, ua, baseline,
                                          schema_version=int(baseline["schemaVersion"]),
                                          expect_valid=True, apply=True)
            except Exception as exc:
                # Baseline differs in topology from every documented preset,
                # so a close before a method reply is an expected restart
                # shape.  Its actual success is established after reconnect.
                evidence.payload["observations"].setdefault("presetRestoreMethodReplyExceptions", {})[preset_name] = str(exc)
            await disconnect_quietly(client)
            client = await reconnect_until(args, evidence, f"preset-{preset_name}-restore-reconnect")
            configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        reconnected, state = await wait_for_stable_config_state(
            args, client, ua, evidence, f"preset-{preset_name}-post-restore")
        client = reconnected
        configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        await assert_hash(configuration, baseline_hash, f"preset {preset_name} baseline restore")
        evidence.passed("preset-baseline-restored", preset=preset_name, state=state)
        return client
    except Exception:
        await disconnect_quietly(client)
        raise


async def verify_presets(args, client, ua, baseline: dict, baseline_hash: str,
                         catalog: object, evidence: Evidence):
    """Exercise only the three v0.5.0 runtime presets, restoring after each."""
    preset_evidence = []
    for preset_name in required_preset_names(catalog):
        try:
            client, result = await apply_preset_and_reconnect(
                args, client, ua, preset_name, evidence)
            preset_evidence.append(result)
            evidence.passed("preset-applied", **result)
        finally:
            # If applying or inspecting a preset failed, do not proceed to
            # another preset.  Attempt recovery first; the outer finally has
            # the same baseline proof as a last line of defence.
            await disconnect_quietly(client)
            client = await restore_preset_baseline(
                args, ua, baseline, baseline_hash, preset_name, evidence)
    evidence.payload["observations"]["presetVerification"] = preset_evidence
    return client


async def restore_baseline(args, baseline: dict, baseline_hash: str, evidence: Evidence) -> None:
    evidence.payload["restore"]["attempted"] = True
    client = None
    try:
        client = await reconnect_until(args, evidence, "best-effort-restore-connect")
        configuration = client.get_node(
            opcua_common.ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        current = await read_export(configuration)
        if document_hash(current) != baseline_hash:
            await upload_and_validate(configuration, opcua_common.ua, baseline,
                                      schema_version=int(baseline["schemaVersion"]),
                                      expect_valid=True, apply=True)
            await disconnect_quietly(client)
            client = await reconnect_until(args, evidence, "best-effort-restore-reconnect")
            configuration = client.get_node(
                opcua_common.ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        client, state = await wait_for_stable_config_state(
            args, client, opcua_common.ua, evidence, "best-effort-restore-stable")
        configuration = client.get_node(
            opcua_common.ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        await assert_hash(configuration, baseline_hash, "best-effort restore")
        evidence.payload["restore"]["restored"] = True
        evidence.payload["restore"]["state"] = state
    except Exception as exc:
        evidence.payload["restore"]["error"] = str(exc)
    finally:
        await disconnect_quietly(client)


async def run(args: argparse.Namespace, evidence: Evidence) -> None:
    opcua_common.load_asyncua()
    ua = opcua_common.ua
    client = await connect(args)
    baseline = None
    baseline_hash = None
    try:
        client, initial_state = await wait_for_stable_config_state(
            args, client, ua, evidence, "initial-config-state")
        evidence.payload["observations"]["verifiedInitialConfigState"] = initial_state
        await capture_management_model(client, ua, evidence)
        if args.expected_software_revision is not None:
            actual_revision = evidence.payload["observations"]["identity"]["softwareRevision"]
            if actual_revision != args.expected_software_revision:
                raise VerificationError(
                    "software revision mismatch: "
                    f"expected {args.expected_software_revision!r}, got {actual_revision!r}"
                )
        configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
        baseline = await read_export(configuration)
        baseline_hash = document_hash(baseline)
        recovery_path = args.recovery_export.resolve()
        recovery_path.parent.mkdir(parents=True, exist_ok=True)
        recovery_path.write_text(opcua_common.serialize_canonical_document(baseline, pretty=True),
                                 encoding="utf-8")
        evidence.payload["observations"]["recoveryExport"] = str(recovery_path)
        evidence.payload["observations"]["recoveryExportSha256"] = baseline_hash
        evidence.passed("recovery-export-written", path=str(recovery_path))

        future = copy.deepcopy(baseline)
        future_schema = int(baseline["schemaVersion"]) + FUTURE_SCHEMA_OFFSET
        future["schemaVersion"] = future_schema
        future_result = await upload_and_validate(configuration, ua, future,
                                                  schema_version=future_schema,
                                                  expect_valid=False, apply=False)
        await assert_hash(configuration, baseline_hash, "future-schema rejection")
        evidence.passed("future-schema-rejected")

        installed_driver_ids = {
            int(descriptor["id"])
            for descriptor in evidence.payload["observations"]["supportedDrivers"].values()
        }
        missing_driver, missing_slot, missing_id = make_missing_driver_candidate(baseline, installed_driver_ids)
        missing_result = await upload_and_validate(configuration, ua, missing_driver,
                                                   schema_version=int(baseline["schemaVersion"]),
                                                   expect_valid=False, apply=False)
        report_text = json.dumps(missing_result.get("report") or {}).lower()
        if "driver" not in report_text or str(missing_id) not in report_text:
            raise VerificationError(f"missing-driver diagnostic did not identify driver: {missing_result}")
        await assert_hash(configuration, baseline_hash, "missing-driver rejection")
        evidence.passed("missing-driver-rejected", channelSlot=missing_slot, driverId=missing_id)

        await verify_no_restart(client, ua, baseline, baseline_hash, evidence)
        client = await verify_restart(args, client, ua, baseline, baseline_hash, evidence)

        if args.verify_presets:
            client = await verify_presets(
                args,
                client,
                ua,
                baseline,
                baseline_hash,
                evidence.payload["observations"]["configPresets"],
                evidence,
            )

        if args.reboot_verify:
            system = client.get_node(ua.NodeId.from_string(SYSTEM_NODE_ID))
            await opcua_common.request_reboot(system)
            await disconnect_quietly(client)
            client = await reconnect_until(args, evidence, "normal-reboot-reconnect")
            configuration = client.get_node(ua.NodeId.from_string(CONFIGURATION_NODE_ID))
            await assert_hash(configuration, baseline_hash, "normal reboot persistence")
            evidence.passed("normal-reboot-persistence")
    finally:
        await disconnect_quietly(client)
        if baseline is not None and baseline_hash is not None:
            await restore_baseline(args, baseline, baseline_hash, evidence)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if args.username and args.password is None:
        args.password = getpass.getpass(f"Password for {args.username}: ")
    evidence = Evidence(args.server_url)
    success = False
    try:
        asyncio.run(run(args, evidence))
        success = not evidence.payload["failed"] and evidence.payload["restore"]["restored"]
        if not success:
            raise VerificationError("baseline restoration was not proven")
        print("verify-v050: PASS")
        return 0
    except Exception as exc:
        evidence.failed("verification", exc)
        print(f"verify-v050: FAIL: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    finally:
        evidence.write(args.evidence, success)
        print(json.dumps({"evidence": str(args.evidence), "success": success}, sort_keys=True))


if __name__ == "__main__":
    raise SystemExit(main())
